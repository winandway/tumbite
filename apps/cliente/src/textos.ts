/** En inglés de EE.UU. la distancia va en millas. */
export function distanciaTexto(km: number, idioma: Idioma): string {
  return idioma === 'en' ? `${(km * 0.621371).toFixed(1)} mi` : `${km.toFixed(1)} km`;
}
